import logging
import asyncio
import google.generativeai as genai
from ..config import GEMINI_KEY

logger = logging.getLogger(__name__)

# Configure API key once
try:
    genai.configure(api_key=GEMINI_KEY)
except Exception:
    logger.exception("Failed to configure Gemini API key.")

# Create a single shared model instance (reused across modules)
try:
    # Keep the same model name to preserve response quality
    model = genai.GenerativeModel("gemini-2.0-flash")
    logger.info("Initialized shared Gemini GenerativeModel instance.")
except Exception as e:
    logger.exception("Failed to initialize shared Gemini model instance: %s", e)
    model = None


async def generate_stream(prompt: str, chunk_size: int = 128):
    """
    Async generator that yields text chunks generated by the model.
    Tries SDK streaming APIs first; falls back to blocking generate_content() and yields slices.
    """
    # Try SDK-native streaming if available
    try:
        if model is None:
            raise RuntimeError("Gemini model instance not initialized.")

        streamer = None
        # The exact SDK streaming method names may vary by version
        if hasattr(model, "generate_content_stream"):
            streamer = model.generate_content_stream(prompt)
        elif hasattr(model, "stream"):
            streamer = model.stream(prompt)
        elif hasattr(genai, "stream"):
            try:
                streamer = genai.stream(prompt)
            except Exception:
                streamer = None

        if streamer is not None:
            # The streamer might be synchronous or asynchronous iterator.
            # Handle both: if it's async, iterate with `async for`; else run in executor.
            try:
                # Try async iteration
                async for event in streamer:
                    text = None
                    try:
                        if hasattr(event, "text"):
                            text = event.text
                        elif hasattr(event, "candidates") and event.candidates:
                            cand = event.candidates[0]
                            if hasattr(cand, "content") and getattr(cand.content, "parts", None):
                                part = cand.content.parts[0]
                                text = getattr(part, "text", None)
                            else:
                                text = getattr(cand, "text", None)
                        else:
                            text = str(event)
                    except Exception:
                        text = str(event)

                    if text:
                        yield text
                return
            except TypeError:
                # Not async iterable; fall through to sync handling below
                pass
            except Exception:
                # If async iteration fails, fall through to sync handling below
                pass

            # Try sync iteration in executor to avoid blocking
            loop = asyncio.get_event_loop()
            try:
                events = await loop.run_in_executor(None, lambda: list(streamer))
                for event in events:
                    text = None
                    try:
                        if hasattr(event, "text"):
                            text = event.text
                        elif hasattr(event, "candidates") and event.candidates:
                            cand = event.candidates[0]
                            if hasattr(cand, "content") and getattr(cand.content, "parts", None):
                                part = cand.content.parts[0]
                                text = getattr(part, "text", None)
                            else:
                                text = getattr(cand, "text", None)
                        else:
                            text = str(event)
                    except Exception:
                        text = str(event)

                    if text:
                        yield text
                return
            except Exception:
                # Fall back to blocking generate_content below
                logger.debug("SDK streaming sync iteration failed; will fallback to generate_content.")
    except Exception as e:
        logger.debug("SDK streaming not available or failed: %s. Using fallback.", e)

    # Fallback: synchronous generation then chunk it
    try:
        loop = asyncio.get_event_loop()
        response = await loop.run_in_executor(None, lambda: model.generate_content(prompt))
        # extract text from response
        full_text = None
        if hasattr(response, "text") and response.text:
            full_text = response.text
        elif hasattr(response, "candidates") and response.candidates:
            cand = response.candidates[0]
            if hasattr(cand, "content") and getattr(cand.content, "parts", None):
                full_text = getattr(cand.content.parts[0], "text", None)
            else:
                full_text = getattr(cand, "text", None)
        if full_text is None:
            full_text = str(response)

        full_text = full_text.strip()
        for i in range(0, len(full_text), chunk_size):
            yield full_text[i : i + chunk_size]
            # slight pause to allow client processing (tunable)
            await asyncio.sleep(0.01)
    except Exception as e:
        logger.exception("Error in fallback generation: %s", e)
        yield "[Error generating response]"


async def generate_text(prompt: str):
    """
    Helper that returns the entire generated text in an async-friendly way.
    """
    if model is None:
        raise RuntimeError("Gemini model not initialized.")

    loop = asyncio.get_event_loop()
    response = await loop.run_in_executor(None, lambda: model.generate_content(prompt))
    if hasattr(response, "text") and response.text:
        return response.text.strip()
    if hasattr(response, "candidates") and response.candidates:
        cand = response.candidates[0]
        if hasattr(cand, "content") and getattr(cand.content, "parts", None):
            return getattr(cand.content.parts[0], "text", "").strip()
        return getattr(cand, "text", "").strip()
    return str(response).strip()


async def warmup_model():
    """
    Perform a small warm-up call at server startup to reduce first-call latency.
    """
    try:
        if model is None:
            logger.warning("Cannot warm up Gemini: model is not initialized.")
            return
        logger.info("Warming up Gemini model with a quick prompt.")
        # consume first chunk only
        async for _ in generate_stream("Say: warmup.", chunk_size=32):
            break
        logger.info("Warmup complete.")
    except Exception:
        logger.exception("Warmup failed (non-fatal).")
